BEGIN;
CREATE TABLE IF NOT EXISTS public.erp_catalogo_opciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  catalogo varchar(80) NOT NULL,
  valor varchar(100) NOT NULL CHECK (length(btrim(valor)) BETWEEN 1 AND 100),
  activo boolean NOT NULL DEFAULT true,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT catalogo_pulsera_activa CHECK (catalogo <> 'entregas_tipo_equipo' OR upper(btrim(valor)) <> 'PULSERA' OR activo)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_erp_catalogo_opciones_valor
  ON public.erp_catalogo_opciones (catalogo, upper(btrim(valor)));
INSERT INTO public.erp_catalogo_opciones (catalogo, valor)
SELECT 'entregas_tipo_equipo', valor FROM (VALUES
 ('PULSERA'),('LAPTOP'),('CARGADOR'),('MOUSE'),('CORREA DE PULSERA'),
 ('MONITOR'),('TABLET'),('MOUSE INALAMBRICO'),('COOLER')
) AS actuales(valor)
ON CONFLICT DO NOTHING;
COMMIT;
