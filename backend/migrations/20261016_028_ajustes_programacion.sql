BEGIN;
ALTER TABLE public.programacion_mantenimiento
  ADD COLUMN IF NOT EXISTS nivel_regular_forzado varchar(2),
  ADD COLUMN IF NOT EXISTS planificacion_ajustada boolean NOT NULL DEFAULT false;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.programacion_mantenimiento'::regclass AND conname='chk_programacion_nivel_forzado') THEN
    ALTER TABLE public.programacion_mantenimiento ADD CONSTRAINT chk_programacion_nivel_forzado
      CHECK(nivel_regular_forzado IS NULL OR nivel_regular_forzado IN ('M1','M2','M3'));
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS public.programacion_mantenimiento_ajustes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  programa_id integer NOT NULL REFERENCES public.programas_mantenimiento(id) ON DELETE RESTRICT,
  programa_unidad_id integer NOT NULL REFERENCES public.programa_mantenimiento_unidades(id) ON DELETE RESTRICT,
  programacion_id integer NOT NULL REFERENCES public.programacion_mantenimiento(id) ON DELETE RESTRICT,
  tipo varchar(30) NOT NULL CHECK(tipo IN ('REPROGRAMACION','ELEVACION_NIVEL','RECALCULO_CIERRE','RECALCULO_PLAN')),
  quincena_anterior date NOT NULL,
  quincena_destino date NOT NULL,
  motivo text NOT NULL,
  creado_por integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  fecha timestamptz NOT NULL DEFAULT now(),
  cambios jsonb NOT NULL CHECK(jsonb_typeof(cambios)='array')
);
CREATE INDEX IF NOT EXISTS idx_ajuste_programacion ON public.programacion_mantenimiento_ajustes(programacion_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_ajuste_unidad ON public.programacion_mantenimiento_ajustes(programa_unidad_id, id DESC);
-- Las protecciones existentes sobre identidad, alcance, órdenes y resultados continúan.
-- También se protegen los dos campos nuevos cuando hay cualquier orden histórica.
CREATE OR REPLACE FUNCTION public.proteger_nivel_forzado_con_ot() RETURNS trigger
LANGUAGE plpgsql SET search_path TO pg_catalog, public AS $$ BEGIN
  IF (NEW.nivel_regular_forzado IS DISTINCT FROM OLD.nivel_regular_forzado
      OR NEW.planificacion_ajustada IS DISTINCT FROM OLD.planificacion_ajustada)
     AND EXISTS (SELECT 1 FROM ordenes_trabajo WHERE programacion_id=OLD.id) THEN
    RAISE EXCEPTION 'La visita % ya tiene historial de órdenes y no admite cambiar el nivel planificado', OLD.id;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_proteger_nivel_forzado_con_ot ON public.programacion_mantenimiento;
CREATE TRIGGER trg_proteger_nivel_forzado_con_ot BEFORE UPDATE ON public.programacion_mantenimiento
FOR EACH ROW EXECUTE FUNCTION public.proteger_nivel_forzado_con_ot();
COMMIT;
