CREATE TABLE public.configuracion_checklist_mantenimiento (
  id smallint PRIMARY KEY CHECK (id = 1),
  exigir_al_cerrar boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO public.configuracion_checklist_mantenimiento (id) VALUES (1);

CREATE TABLE public.catalogo_actividades_mantenimiento (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_equipo varchar(30) NOT NULL CHECK (tipo_equipo IN ('CAMARAS','COPILOTO','RADIO_BASE')),
  nivel_origen varchar(2) NOT NULL CHECK (nivel_origen IN ('M1','M2','M3')),
  descripcion text NOT NULL CHECK (NULLIF(BTRIM(descripcion),'') IS NOT NULL),
  orden integer NOT NULL DEFAULT 0 CHECK (orden >= 0),
  activo boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE FUNCTION public.actualizar_fecha_catalogo_checklist() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := CURRENT_TIMESTAMP; RETURN NEW; END $$;
CREATE TRIGGER trg_actualizar_fecha_catalogo_checklist BEFORE UPDATE ON public.catalogo_actividades_mantenimiento
  FOR EACH ROW EXECUTE FUNCTION public.actualizar_fecha_catalogo_checklist();
CREATE INDEX idx_catalogo_checklist_familia_nivel
  ON public.catalogo_actividades_mantenimiento (tipo_equipo,nivel_origen,orden) WHERE activo;

CREATE TABLE public.ordenes_trabajo_detalle_actividades (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_trabajo_detalle_id integer NOT NULL REFERENCES public.ordenes_trabajo_detalle(id) ON DELETE RESTRICT,
  actividad_catalogo_id integer NOT NULL REFERENCES public.catalogo_actividades_mantenimiento(id) ON DELETE RESTRICT,
  descripcion_snapshot text NOT NULL CHECK (NULLIF(BTRIM(descripcion_snapshot),'') IS NOT NULL),
  nivel_origen_snapshot varchar(2) NOT NULL CHECK (nivel_origen_snapshot IN ('M1','M2','M3')),
  orden_snapshot integer NOT NULL CHECK (orden_snapshot >= 0),
  estado varchar(12) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','REALIZADO','NO_APLICA')),
  observacion text,
  actualizado_por_id integer REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  actualizado_en timestamptz,
  -- La exigencia se congela al crear el checklist; no se impone a órdenes antiguas.
  exigible_al_cierre boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_checklist_detalle_actividad UNIQUE (orden_trabajo_detalle_id,actividad_catalogo_id)
);

CREATE FUNCTION public.proteger_actividad_checklist() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE detalle_id integer; estado_ot text; familia text; nivel text; catalogo record;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Las actividades históricas no se eliminan';
  END IF;
  detalle_id := NEW.orden_trabajo_detalle_id;
  SELECT o.estado,e.tipo_equipo,e.nivel_mantenimiento INTO estado_ot,familia,nivel
  FROM public.ordenes_trabajo_detalle d
  JOIN public.ordenes_trabajo o ON o.id=d.orden_trabajo_id
  JOIN public.programacion_mantenimiento_equipos e ON e.id=d.programacion_equipo_id
  WHERE d.id=detalle_id FOR UPDATE OF o;
  IF estado_ot IS DISTINCT FROM 'ABIERTA' THEN
    RAISE EXCEPTION 'El checklist solo se modifica con la orden abierta';
  END IF;
  IF TG_OP='INSERT' THEN
    SELECT * INTO catalogo FROM public.catalogo_actividades_mantenimiento WHERE id=NEW.actividad_catalogo_id FOR SHARE;
    IF catalogo.id IS NULL OR NOT catalogo.activo OR catalogo.tipo_equipo<>familia
       OR catalogo.nivel_origen>nivel OR familia NOT IN ('CAMARAS','COPILOTO','RADIO_BASE') THEN
      RAISE EXCEPTION 'La actividad no pertenece al alcance del apartado';
    END IF;
    NEW.descripcion_snapshot := catalogo.descripcion;
    NEW.nivel_origen_snapshot := catalogo.nivel_origen;
    NEW.orden_snapshot := catalogo.orden;
    NEW.estado := 'PENDIENTE'; NEW.observacion := NULL;
    NEW.actualizado_por_id := NULL; NEW.actualizado_en := NULL;
    SELECT exigir_al_cerrar INTO NEW.exigible_al_cierre
      FROM public.configuracion_checklist_mantenimiento WHERE id=1 FOR SHARE;
    IF NEW.exigible_al_cierre IS NULL THEN RAISE EXCEPTION 'Falta la configuración de checklist'; END IF;
  ELSE
    IF ROW(NEW.id,NEW.orden_trabajo_detalle_id,NEW.actividad_catalogo_id,
      NEW.descripcion_snapshot,NEW.nivel_origen_snapshot,NEW.orden_snapshot,
      NEW.exigible_al_cierre,NEW.created_at)
      IS DISTINCT FROM ROW(OLD.id,OLD.orden_trabajo_detalle_id,OLD.actividad_catalogo_id,
      OLD.descripcion_snapshot,OLD.nivel_origen_snapshot,OLD.orden_snapshot,
      OLD.exigible_al_cierre,OLD.created_at) THEN
      RAISE EXCEPTION 'El contenido histórico del checklist es inmutable';
    END IF;
    NEW.actualizado_en := CURRENT_TIMESTAMP;
    NEW.updated_at := CURRENT_TIMESTAMP;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_proteger_actividad_checklist BEFORE INSERT OR UPDATE OR DELETE
  ON public.ordenes_trabajo_detalle_actividades FOR EACH ROW EXECUTE FUNCTION public.proteger_actividad_checklist();

CREATE FUNCTION public.materializar_checklist_detalle() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE familia text; nivel text; exigir boolean; cantidad integer;
BEGIN
  SELECT tipo_equipo,nivel_mantenimiento INTO familia,nivel
    FROM public.programacion_mantenimiento_equipos WHERE id=NEW.programacion_equipo_id;
  IF familia NOT IN ('CAMARAS','COPILOTO','RADIO_BASE') THEN RETURN NEW; END IF;
  SELECT exigir_al_cerrar INTO exigir FROM public.configuracion_checklist_mantenimiento WHERE id=1 FOR SHARE;
  IF exigir IS NULL THEN RAISE EXCEPTION 'Falta la configuración de checklist'; END IF;
  INSERT INTO public.ordenes_trabajo_detalle_actividades (
    orden_trabajo_detalle_id,actividad_catalogo_id,descripcion_snapshot,
    nivel_origen_snapshot,orden_snapshot,exigible_al_cierre
  ) SELECT NEW.id,c.id,c.descripcion,c.nivel_origen,c.orden,exigir
    FROM public.catalogo_actividades_mantenimiento c
    WHERE c.activo AND c.tipo_equipo=familia AND c.nivel_origen<=nivel
    ON CONFLICT (orden_trabajo_detalle_id,actividad_catalogo_id) DO NOTHING;
  GET DIAGNOSTICS cantidad=ROW_COUNT;
  IF exigir AND cantidad=0 THEN
    RAISE EXCEPTION 'No hay actividades aprobadas para el apartado % %',familia,nivel;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_materializar_checklist_detalle AFTER INSERT ON public.ordenes_trabajo_detalle
  FOR EACH ROW EXECUTE FUNCTION public.materializar_checklist_detalle();

CREATE FUNCTION public.validar_checklist_cierre() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.estado='CERRADA' AND OLD.estado IS DISTINCT FROM 'CERRADA' AND EXISTS (
    SELECT 1 FROM public.ordenes_trabajo_detalle_actividades a
    JOIN public.ordenes_trabajo_detalle d ON d.id=a.orden_trabajo_detalle_id
    WHERE d.orden_trabajo_id=NEW.id AND a.exigible_al_cierre
      AND a.estado IN ('PENDIENTE','NO_APLICA') AND NULLIF(BTRIM(a.observacion),'') IS NULL
  ) THEN
    RAISE EXCEPTION 'Las actividades pendientes o no aplicables necesitan motivo para cerrar';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_validar_checklist_cierre BEFORE UPDATE OF estado ON public.ordenes_trabajo
  FOR EACH ROW EXECUTE FUNCTION public.validar_checklist_cierre();
COMMIT;
