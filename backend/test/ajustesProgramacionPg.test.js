// Prueba de integración sin conexión a Neon. PGlite es opcional y solo se usa en pruebas.
// PGLITE_TEST_MODULE puede apuntar a una instalación local de @electric-sql/pglite.
import assert from 'node:assert/strict';
import { test, mock } from 'node:test';
import { readFile } from 'node:fs/promises';
import { indice, quincena, MOTIVOS } from '../src/modules/programas/programacion/ajustes/planificador.js';
import { frecuencias } from './helpers/ajustesFixtures.js';
let PGlite;
try {
  ({
    PGlite
  } = await import(process.env.PGLITE_TEST_MODULE || '@electric-sql/pglite'));
} catch (error) {
  if (error.code !== 'ERR_MODULE_NOT_FOUND') throw error;
}
test('PostgreSQL local: migración, cascadas, auditoría, aislamiento y rollback', {
  skip: !PGlite && 'Instale PGlite para ejecutar la integración local.'
}, async t => {
  const db = new PGlite();
  let falloAuditoria = false;
  const client = {
    query: (sql, params) => db.query(sql, params),
    release() {}
  };
  const pool = {
    ...client,
    connect: async () => client
  };
  mock.module('../src/config/database.js', {
    namedExports: {
      pool
    }
  });
  mock.module('../src/services/auditService.js', {
    namedExports: {
      logAction: async (...args) => {
        assert.equal(args.at(-1).client, client);
        if (falloAuditoria) throw new Error('Auditoría no disponible');
      }
    }
  });
  const {
    aplicarAjuste,
    destinosConDesplazamiento,
    recalcularTrasCierre
  } = await import('../src/modules/programas/programacion/ajustes/service.js');
  const {
    cargarInsumos,
    generar,
    materializar
  } = await import('../scripts/ti-pr-01/generador-nucleo.mjs');
  const migration = await readFile(new URL('../migrations/20261016_028_ajustes_programacion.sql', import.meta.url), 'utf8');
  const historico = await readFile(new URL('../migrations/20260928_016_ti_pr_01_alcance_historico.sql', import.meta.url), 'utf8');
  const funciones = ['congelar_visita_con_ot', 'congelar_alcance_programado'].map(nombre => {
    const match = historico.match(new RegExp(`CREATE OR REPLACE FUNCTION ${nombre}\\(\\)[\\s\\S]*?END \\$\\$;`));
    assert.ok(match, `Función histórica ${nombre}`);
    return match[0];
  });
  const req = {
    user: {
      id: 8,
      rol: 'ti',
      username: 'tecnico'
    },
    headers: {},
    ip: '127.0.0.1'
  };
  const hoy = (await db.query("SELECT (now() AT TIME ZONE 'America/Lima')::date::text AS fecha")).rows[0].fecha;
  const q = quincena(indice(hoy)),
    siguiente = quincena(indice(q) + 1);
  const inicial = async (resultado = null) => {
    await db.exec(`DROP SCHEMA public CASCADE; CREATE SCHEMA public;
      CREATE TABLE programas_mantenimiento(id int PRIMARY KEY);
      CREATE TABLE usuarios(id int PRIMARY KEY);
      CREATE TABLE programa_mantenimiento_unidades(id int PRIMARY KEY,programa_id int REFERENCES programas_mantenimiento,placa text,habilitado boolean NOT NULL DEFAULT true,familias_confirmadas text[] NOT NULL DEFAULT ARRAY[]::text[]);
      CREATE TABLE programas_mantenimiento_versiones(id int PRIMARY KEY,programa_id int,version text,estado text,vigencia_desde date,vigencia_hasta date);
      CREATE TABLE programa_mantenimiento_frecuencias(programa_id int,tipo_equipo varchar,nivel_mantenimiento varchar,frecuencia_quincenas int,PRIMARY KEY(programa_id,tipo_equipo,nivel_mantenimiento));
      CREATE TABLE programa_mantenimiento_unidad_ciclos(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,programa_unidad_id int,tipo_equipo text,nivel_mantenimiento text,ultima_quincena date,ultima_fecha_real date,orden_trabajo_detalle_id int);
      CREATE TABLE programa_mantenimiento_unidad_anclas(programa_unidad_id int,tipo_equipo text,nivel_mantenimiento text,quincena_ancla date);
      CREATE TABLE vehiculo_equipos(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,placa text,tipo_equipo text,estado_inventario text,marca text);
      CREATE TABLE programacion_mantenimiento(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,programa_id int REFERENCES programas_mantenimiento,programa_unidad_id int REFERENCES programa_mantenimiento_unidades,version_programa_id int REFERENCES programas_mantenimiento_versiones,quincena_programada date NOT NULL,quincena_reprogramada date,
        quincena_efectiva date GENERATED ALWAYS AS (COALESCE(quincena_reprogramada,quincena_programada)) STORED,estado text NOT NULL,fecha_ejecucion date,observaciones text,created_at timestamptz DEFAULT now(),updated_at timestamptz DEFAULT now(),
        CHECK(extract(day FROM quincena_programada) IN (1,16)),CHECK(quincena_reprogramada IS NULL OR extract(day FROM quincena_reprogramada) IN(1,16)));
      CREATE UNIQUE INDEX uq_programacion_unidad_quincena_efectiva ON programacion_mantenimiento(programa_unidad_id,quincena_efectiva) WHERE estado<>'CANCELADO';
      CREATE TABLE programacion_mantenimiento_equipos(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,programacion_id int REFERENCES programacion_mantenimiento,programa_id int,tipo_equipo varchar,nivel_mantenimiento varchar,FOREIGN KEY(programa_id,tipo_equipo,nivel_mantenimiento) REFERENCES programa_mantenimiento_frecuencias);
      CREATE TABLE ordenes_trabajo(id int PRIMARY KEY,programacion_id int REFERENCES programacion_mantenimiento,estado text);
      CREATE TABLE ordenes_trabajo_detalle(id int PRIMARY KEY,programacion_equipo_id int);
      INSERT INTO programas_mantenimiento VALUES(1),(2);INSERT INTO usuarios VALUES(8);
      INSERT INTO programa_mantenimiento_unidades VALUES(10,1,'V0Y781'),(20,1,'V0I941');
      INSERT INTO programas_mantenimiento_versiones VALUES(1,1,'01','VIGENTE','2020-01-01',NULL);`);
    for (const f of frecuencias) await db.query('INSERT INTO programa_mantenimiento_frecuencias VALUES(1,$1,$2,$3)', [f.tipo_equipo, f.nivel_mantenimiento, f.frecuencia_quincenas]);
    for (const u of [10, 20]) for (const f of frecuencias) {
      await db.query('INSERT INTO programa_mantenimiento_unidad_anclas VALUES($1,$2,$3,$4)', [u, f.tipo_equipo, f.nivel_mantenimiento, quincena(indice(q) - 1)]);
    }
    for (const placa of ['V0Y781', 'V0I941']) for (const tipo of ['CAMARA_INTERNA', 'CAMARA_EXTERNA', 'COPILOTO', 'RADIO_BASE']) await db.query("INSERT INTO vehiculo_equipos(placa,tipo_equipo,estado_inventario) VALUES($1,$2,'INSTALADO')", [placa, tipo]);
    for (let i = 0; i < 18; i++) for (const u of [10, 20]) {
      const id = u * 100 + i;
      await db.query("INSERT INTO programacion_mantenimiento(id,programa_id,programa_unidad_id,version_programa_id,quincena_programada,estado) VALUES($1,1,$2,1,$3,'PROYECTADO')", [id, u, quincena(indice(q) + i)]);
      for (const f of ['CAMARAS', 'COPILOTO', 'RADIO_BASE']) await db.query('INSERT INTO programacion_mantenimiento_equipos(programacion_id,programa_id,tipo_equipo,nivel_mantenimiento) VALUES($1,1,$2,$3)', [id, f, i === 5 ? 'M2' : i === 11 ? 'M3' : 'M1']);
    }
    await db.exec('SELECT setval(pg_get_serial_sequence(\'programacion_mantenimiento\',\'id\'),3000)');
    if (resultado) await db.query('UPDATE programacion_mantenimiento SET estado=$1 WHERE id=1000', [resultado]);
    for (const f of funciones) await db.exec(f);
    await db.exec(`CREATE TRIGGER trg_congelar_visita_con_ot BEFORE INSERT OR UPDATE ON programacion_mantenimiento FOR EACH ROW EXECUTE FUNCTION congelar_visita_con_ot();
      CREATE TRIGGER trg_congelar_alcance_programado BEFORE INSERT OR UPDATE OR DELETE ON programacion_mantenimiento_equipos FOR EACH ROW EXECUTE FUNCTION congelar_alcance_programado();`);
    await db.exec(migration);
    falloAuditoria = false;
  };
  const snapshot = async () => JSON.stringify((await db.query(`SELECT * FROM (SELECT 'visita' AS tipo,to_jsonb(p) AS datos FROM programacion_mantenimiento p UNION ALL
      SELECT 'equipo',to_jsonb(e) FROM programacion_mantenimiento_equipos e UNION ALL
      SELECT 'ajuste',to_jsonb(a) FROM programacion_mantenimiento_ajustes a) datos_ordenados ORDER BY tipo,datos::text`)).rows);
  const ajustar = datos => aplicarAjuste({
    programaId: 1,
    visitaId: 1000,
    req,
    ...datos
  });
  try {
    await t.test('La migración se puede repetir sin cambiar datos', async () => {
      await inicial();
      const antes = await snapshot();
      await db.exec(migration);
      assert.equal(await snapshot(), antes);
    });
    await t.test('La previsualización ofrece destinos ocupados sin escribir', async () => {
      await inicial();
      const antes = await snapshot();
      const r = await destinosConDesplazamiento(1, 1000);
      assert.equal(r.destinos.length, 1);
      assert.equal(r.solo_siguiente_quincena, true);
      assert.equal(r.destinos[0].quincena, siguiente);
      assert.equal(r.destinos.find(d => d.quincena === siguiente).disponible, true);
      assert.ok(r.destinos.find(d => d.quincena === siguiente).desplazadas > 0);
      assert.equal(await snapshot(), antes);
    });
    await t.test('Reprograma y desplaza la cadena conservando unique, equipos, anclas y otra placa', async () => {
      await inicial();
      const otra = JSON.stringify((await db.query('SELECT * FROM programacion_mantenimiento WHERE programa_unidad_id=20 ORDER BY id')).rows);
      const r = await ajustar({
        destino: siguiente,
        motivo: MOTIVOS[1]
      });
      assert.ok(r.cambios.length > 1);
      assert.equal((await db.query('SELECT quincena_efectiva::text AS q FROM programacion_mantenimiento WHERE id=1001')).rows[0].q, quincena(indice(q) + 2));
      assert.equal(JSON.stringify((await db.query('SELECT * FROM programacion_mantenimiento WHERE programa_unidad_id=20 ORDER BY id')).rows), otra);
      assert.equal((await db.query('SELECT count(*)::int AS n FROM programa_mantenimiento_unidad_ciclos')).rows[0].n, 0);
      assert.equal((await db.query('SELECT count(*)::int AS n FROM programacion_mantenimiento_equipos')).rows[0].n, 108);
      assert.equal((await db.query('SELECT count(*)::int AS n FROM programa_mantenimiento_unidad_anclas')).rows[0].n, 20);
      const antes = await snapshot();
      await ajustar({
        destino: siguiente,
        motivo: MOTIVOS[1]
      });
      assert.equal(await snapshot(), antes);
    });
    await t.test('La API rechaza un salto o adelanto sin mover datos', async () => {
      await inicial();
      const antes = await snapshot();
      await assert.rejects(ajustar({ visitaId: 1002, destino: q, motivo: MOTIVOS[0] }), /siguiente quincena/);
      await assert.rejects(ajustar({ destino: quincena(indice(q) + 2), motivo: MOTIVOS[0] }), /siguiente quincena/);
      assert.equal(await snapshot(), antes);
    });
    await t.test('M3 actualiza las siguientes quincenas sin inventar ejecución', async () => {
      await inicial();
      await ajustar({
        nuevoNivel: 'M3'
      });
      const rows = (await db.query("SELECT p.id,e.nivel_mantenimiento FROM programacion_mantenimiento p JOIN programacion_mantenimiento_equipos e ON e.programacion_id=p.id WHERE p.programa_unidad_id=10 AND e.tipo_equipo='CAMARAS' ORDER BY p.id")).rows;
      assert.equal(rows[0].nivel_mantenimiento, 'M3');
      assert.equal(rows[5].nivel_mantenimiento, 'M1');
      assert.equal(rows[6].nivel_mantenimiento, 'M2');
      assert.equal(rows[12].nivel_mantenimiento, 'M3');
      assert.equal((await db.query('SELECT count(*)::int AS n FROM programacion_mantenimiento WHERE fecha_ejecucion IS NOT NULL')).rows[0].n, 0);
      const antes = await snapshot();
      await ajustar({
        nuevoNivel: 'M3'
      });
      assert.equal(await snapshot(), antes);
    });
    await t.test('Si falla auditoría, se revierten todas las fechas, niveles y movimientos', async () => {
      await inicial();
      const antes = await snapshot();
      falloAuditoria = true;
      await assert.rejects(ajustar({
        destino: siguiente,
        motivo: MOTIVOS[0]
      }), /Auditoría/);
      assert.equal(await snapshot(), antes);
    });
    await t.test('OT de otra visita bloquea la cascada completa sin cambios parciales', async () => {
      await inicial();
      await db.exec("INSERT INTO ordenes_trabajo VALUES(1,1002,'ABIERTA')");
      const antes = await snapshot();
      await assert.rejects(ajustar({
        destino: siguiente,
        motivo: MOTIVOS[0]
      }), /orden|historial/);
      assert.equal(await snapshot(), antes);
    });
    await t.test('Las protecciones históricas siguen activas en PostgreSQL', async () => {
      await inicial();
      await db.exec("INSERT INTO ordenes_trabajo VALUES(1,1000,'CERRADA')");
      await assert.rejects(db.query("UPDATE programacion_mantenimiento_equipos SET nivel_mantenimiento='M3' WHERE programacion_id=1000"), /HISTORICO/);
      await assert.rejects(db.query("UPDATE programacion_mantenimiento SET nivel_regular_forzado='M3' WHERE id=1000"), /historial/);
    });
    await t.test('Motivo fuera del catálogo y programa ajeno se rechazan', async () => {
      await inicial();
      const antes = await snapshot();
      await assert.rejects(ajustar({
        destino: siguiente,
        motivo: 'Libre'
      }), /motivo válido/);
      await assert.rejects(ajustar({
        programaId: 2,
        nuevoNivel: 'M3'
      }), /no encontrada/);
      assert.equal(await snapshot(), antes);
    });
    await t.test('Después de cerrar, la proyección usa los ciclos reales y conserva el resultado histórico', async () => {
      await inicial('EJECUTADO');
      await db.exec("INSERT INTO ordenes_trabajo VALUES(1,1000,'CERRADA')");
      for (const f of frecuencias.filter(f => f.tipo_equipo !== 'GPS')) await db.query(`INSERT INTO programa_mantenimiento_unidad_ciclos
        (programa_unidad_id,tipo_equipo,nivel_mantenimiento,ultima_quincena) VALUES(10,$1,$2,$3::date)`, [f.tipo_equipo, f.nivel_mantenimiento, q]);
      await db.query('BEGIN');
      const n = await recalcularTrasCierre(client, 1, 1000, 8);
      await db.query('COMMIT');
      assert.ok(n > 0);
      assert.equal((await db.query('SELECT estado FROM programacion_mantenimiento WHERE id=1000')).rows[0].estado, 'EJECUTADO');
      const niveles = (await db.query("SELECT p.id,e.nivel_mantenimiento FROM programacion_mantenimiento p JOIN programacion_mantenimiento_equipos e ON e.programacion_id=p.id WHERE p.id IN(1005,1006,1012) AND e.tipo_equipo='CAMARAS' ORDER BY p.id")).rows;
      assert.deepEqual(niveles.map(x => x.nivel_mantenimiento), ['M1', 'M2', 'M3']);
      assert.ok((await db.query("SELECT count(*)::int AS n FROM programacion_mantenimiento_ajustes WHERE tipo='RECALCULO_CIERRE'")).rows[0].n > 0);
    });
    await t.test('Una generación leída antes de un ajuste no puede escribir el plan obsoleto', async () => {
      await inicial();
      const antesDeAjuste = await cargarInsumos(client, 1);
      const viejo = generar(antesDeAjuste, q, quincena(indice(q) + 23));
      await ajustar({
        nuevoNivel: 'M3'
      });
      const antes = await snapshot();
      await db.query('BEGIN');
      await assert.rejects(materializar(client, viejo.seguras.filter(v => v.unidad === 10)), /cambió durante la generación/);
      await db.query('ROLLBACK');
      assert.equal(await snapshot(), antes);
    });
    await t.test('Generar después de ajustar no restaura niveles ni rellena el origen', async () => {
      await inicial();
      await ajustar({
        destino: siguiente,
        motivo: MOTIVOS[0]
      });
      let ins = await cargarInsumos(client, 1);
      let r = generar(ins, q, quincena(indice(q) + 23));
      assert.ok(r.visitas.filter(v => v.unidad === 10).every(v => v.quincena > quincena(indice(q) + 18)));
      await db.query('BEGIN');
      await materializar(client, r.seguras);
      await db.query('COMMIT');
      ins = await cargarInsumos(client, 1);
      r = generar(ins, q, quincena(indice(q) + 23));
      assert.equal(r.seguras.filter(v => v.unidad === 10).length, 0);
    });
  } finally {
    await db.close();
  }
});
